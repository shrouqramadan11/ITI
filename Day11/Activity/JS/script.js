let number = -5;

// Positive or Negative checker

if (number > 0) {
    console.log("Positive number");
}
else if (number < 0) {
    console.log("Negative number");
}

else {
    console.log("number is 0");
}

//Even or Odd checker

if (number % 2 == 0){
    console.log("Even number")
}
else if (number % 2 != 0){
    console.log("Odd number")
}